const generateHistory = (basePrice, volatility = 0.02, days = 30) => {
  const history = [];
  let price = basePrice * (1 - volatility * (days / 2));
  const now = new Date();

  for (let i = days; i >= 0; i--) {
    const date = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    // Random walk with mean reversion
    const changePct = (Math.random() - 0.49) * volatility;
    price = Math.max(10, price * (1 + changePct));
    const dayVolume = Math.floor(500000 + Math.random() * 2000000);
    history.push({
      timestamp: date,
      price: Number(price.toFixed(2)),
      volume: dayVolume
    });
  }
  return history;
};

